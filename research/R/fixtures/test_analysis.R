args <- commandArgs(trailingOnly = TRUE)
root <- normalizePath(if (length(args)) args[1] else "research/R")
source(file.path(root, "common", "analysis.R"))
x <- validate_accuracy(read_dataset(file.path(root, "fixtures", "accuracy.csv"), c("case_id", "configuration", "prediction", "ground_truth", "status")))
m <- metrics(x[x$configuration == "native", ])
stopifnot(m[["tp"]] == 1, m[["fp"]] == 1, m[["fn"]] == 1, m[["tn"]] == 1, m[["precision"]] == .5, m[["recall"]] == .5, m[["f1"]] == .5, m[["fpr"]] == .5, m[["fnr"]] == .5, m[["coverage"]] == .8, m[["unknown_partial_rate"]] == .2)
stopifnot(is.na(metrics(x[x$status != "COMPLETE", ])[['precision']]))
x$correct <- ifelse(x$status == "COMPLETE", as.numeric(x$prediction == x$ground_truth), NA_real_)
p <- paired_difference(x, "correct", "native", "semantic", 100)
stopifnot(p$pairs == 4, p$difference == .5)
stopifnot(identical(bootstrap_ci(x, function(z) mean(z$ground_truth), 100), bootstrap_ci(x, function(z) mean(z$ground_truth), 100)))
stopifnot(inherits(try(validate_accuracy(rbind(x, x[1, ])), silent = TRUE), "try-error"))
bad <- x; bad$ground_truth[bad$case_id == "case1" & bad$configuration == "semantic"] <- 0
stopifnot(inherits(try(validate_accuracy(bad), silent = TRUE), "try-error"))
cat("Synthetic fixture assertions passed\n")
